const adminItems = [
  { label: "Translation Check", href: "/translation-check", icon: "languages" },
  { label: "Settings", href: "/settings", icon: "settings" },
];

export function Sidebar() {
  const pathname = usePathname();
  const { data } = useSession();
  const user = data?.user;

  const items = user?.role === "admin" ? [...navItems, ...adminItems] : navItems;

  return (
    <aside className="flex h-full w-60 flex-col border-r border-border bg-white">
      <div className="flex h-16 items-center px-6">
        <h2 className="text-lg font-semibold text-night-blue">
          Travel Experts
        </h2>
      </div>

      <nav className="flex-1 px-3 py-4">
        <ul className="space-y-1">
          {items.map((item) => {
            const isActive = pathname.startsWith(item.href);
            return (
              <li key={item.href}>
                <Link
                  href={item.href}
                  className={cn(
                    "flex items-center gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors",
                    isActive
                      ? "bg-sand-light text-night-blue"
                      : "text-muted-foreground hover:bg-sand-light/50 hover:text-foreground"
                  )}
                >
                  <NavIcon name={item.icon} />
                  {item.label}
                </Link>
              </li>
            );
          })}
        </ul>
      </nav>

      <div className="border-t border-border px-3 py-4">
        <div className="px-3 text-xs text-muted-foreground">
          {user?.email}
        </div>
      </div>
    </aside>
  );
}

